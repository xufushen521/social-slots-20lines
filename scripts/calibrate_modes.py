def main() -> None:
    config = load_config(Path(__file__).resolve().parents[1] / "config.json")
    base = config["presets"]["beginner"]
    for name, table in TABLES.items():
        preset = deepcopy(base)
        preset["reels"]["strips"] = [STRIPS["B2"].copy() for _ in range(5)]
        for symbol, pays in table.items():
            preset["symbols"][symbol]["pays"] = pays
        result = simulate_preset(preset, config["lines"], spins=100_000, seed=11)
        print(
            name,
            f"exact={exact_line_rtp(preset):.4%}",
            f"base={result['base_rtp']:.4%}",
            f"total={result['total_rtp']:.4%}",
            f"hit={result['hit_rate']:.4%}",
            f"sd={result['sd']:.4f}",
        )


if __name__ == "__main__":
    main()
